// ===== SkillLoop AI — Classroom & 60-Student Dataset =====

export interface TeacherProfile {
  name: string
  email: string
  department: string
  designation: string
  experience: string
  subjects: string[]
  class: string
  avatarInitials: string
}

export interface ClassroomInfo {
  id: string
  course: string
  className: string
  academicYear: string
  totalStudents: number
  teacherName: string
  subject: string
  teacherRole: string
}

export interface StudentRecord {
  id: string
  name: string
  rollNumber: string
  email: string
  course: string
  year: number
  classId: string
  overallMastery: number
  attendance: number           // 0-100%
  streak: number               // days
  recursionMastery: number
  arraysMastery: number
  searchingMastery: number
  sortingMastery: number
  collectionsMastery: number
  pythonMastery: number
  javaMastery: number
  mlMastery: number
  aiMastery: number
  aiAssistanceIndex: number    // 0-100 (higher = more AI dependent)
  assessmentScore: number      // latest score
  lastActive: string
  interventionRequired: boolean
  interventionReason: string
  interventionPriority: 'Critical' | 'High' | 'Medium' | 'Low'
  projectProgress: number      // 0-100%
}

export interface InterventionRecord {
  id: string
  studentId: string
  studentName: string
  rollNumber: string
  skill: string
  reason: string
  priority: 'Critical' | 'High' | 'Medium' | 'Low'
  recommendedAction: string
  status: 'Pending' | 'In Progress' | 'Completed'
  createdAt: string
  assignedTo?: string
}

export interface ClassroomActivityRecord {
  id: string
  timestamp: string
  studentName: string
  event: string
  type: 'mastery' | 'assessment' | 'intervention' | 'project'
}

